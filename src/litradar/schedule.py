"""Scheduler integration: a wrapper script plus the native command for each OS.

The engine itself never runs in the background — reliability comes from the OS
scheduler.  We generate the wrapper, and only register it when the user passes
``--apply``; printing the exact command is the default so nothing surprising happens
to someone's task list.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path
from typing import Any

from .config import Config

TASK_NAME = "Litradar Daily"
MAC_LABEL = "com.litradar.daily"


def platform_key() -> str:
    if sys.platform.startswith("win"):
        return "win32"
    if sys.platform == "darwin":
        return "darwin"
    return "linux"


def wrapper_name(platform: str | None = None) -> str:
    return "run-daily.cmd" if (platform or platform_key()) == "win32" else "run-daily.sh"


def wrapper_path(vault: Path | str, platform: str | None = None) -> Path:
    return Path(vault).expanduser().resolve() / ".litradar" / wrapper_name(platform)


def _time(cfg: Config) -> tuple[int, int]:
    raw = str(cfg.get("schedule.time", "09:00") or "09:00")
    try:
        hour, minute = raw.split(":")[:2]
        return int(hour), int(minute)
    except ValueError:
        return 9, 0


def write_wrapper(vault: Path | str, cfg: Config, python_exe: str | None = None) -> Path:
    vault = Path(vault).expanduser().resolve()
    python_exe = python_exe or sys.executable
    target = wrapper_path(vault)
    target.parent.mkdir(parents=True, exist_ok=True)
    timezone = cfg.tz
    extra = ""
    if timezone:
        extra = ""  # the engine reads schedule.tz from config; kept for readability
    args = (
        f'-m litradar run --vault "{vault}" --window yesterday --llm --jsonl '
        f"--catch-up --max-days 3{extra}"
    )
    if platform_key() == "win32":
        content = (
            "@echo off\r\n"
            "rem generated by `litradar schedule install` — edit config.yaml, not this file\r\n"
            "chcp 65001 >nul\r\n"
            f'cd /d "{vault}"\r\n'
            "rem Secrets for unattended runs (e.g. LITRADAR_API_KEY) live outside the vault\r\n"
            'if exist "%USERPROFILE%\\.config\\litradar\\env.cmd" call "%USERPROFILE%\\.config\\litradar\\env.cmd"\r\n'
            "set PYTHONIOENCODING=utf-8\r\n"
            "set PYTHONUTF8=1\r\n"
            "set PYTHONUNBUFFERED=1\r\n"
            f'"{python_exe}" {args} >> ".litradar\\logs\\daily.log" 2>&1\r\n'
            "exit /b %ERRORLEVEL%\r\n"
        )
    else:
        content = (
            "#!/bin/sh\n"
            "# generated by `litradar schedule install` — edit config.yaml, not this file\n"
            f'cd "{vault}" || exit 1\n'
            "# Secrets for unattended runs (e.g. LITRADAR_API_KEY) live outside the vault.\n"
            'if [ -f "$HOME/.config/litradar/env" ]; then . "$HOME/.config/litradar/env"; fi\n'
            "export PYTHONIOENCODING=utf-8\n"
            "export PYTHONUTF8=1\n"
            "export PYTHONUNBUFFERED=1\n"
            f'exec "{python_exe}" {args} >> ".litradar/logs/daily.log" 2>&1\n'
        )
    target.write_text(content, encoding="utf-8", newline="")
    if platform_key() != "win32":
        try:
            target.chmod(0o755)
        except OSError:
            pass
    return target


def mac_plist_path() -> Path:
    return Path.home() / "Library" / "LaunchAgents" / f"{MAC_LABEL}.plist"


def mac_plist(wrapper: Path, cfg: Config) -> str:
    hour, minute = _time(cfg)
    log = wrapper.parent / "logs" / "daily.log"
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>{MAC_LABEL}</string>
  <key>ProgramArguments</key>
  <array><string>/bin/sh</string><string>{wrapper}</string></array>
  <key>StartCalendarInterval</key>
  <dict><key>Hour</key><integer>{hour}</integer><key>Minute</key><integer>{minute}</integer></dict>
  <key>RunAtLoad</key><false/>
  <key>StandardOutPath</key><string>{log}</string>
  <key>StandardErrorPath</key><string>{log}</string>
</dict>
</plist>
"""


def cron_line(wrapper: Path, cfg: Config) -> str:
    hour, minute = _time(cfg)
    log = wrapper.parent / "logs" / "daily.log"
    return f'{minute} {hour} * * * /bin/sh "{wrapper}" >> "{log}" 2>&1'


def print_commands(vault: Path | str, cfg: Config) -> list[str]:
    """Human-readable install instructions for the current platform."""
    wrapper = write_wrapper(vault, cfg)
    key = platform_key()
    hour, minute = _time(cfg)
    if key == "win32":
        return [
            f"wrote {wrapper}",
            "提示：把 `set LITRADAR_API_KEY=sk-...` 写进 "
            "%USERPROFILE%\\.config\\litradar\\env.cmd（不要放进 vault）",
            'schtasks /Create /TN "Litradar Daily" /SC DAILY /ST '
            f'{hour:02d}:{minute:02d} /F /TR "\\"{wrapper}\\""',
            'schtasks /Query /TN "Litradar Daily" /FO LIST',
        ]
    if key == "darwin":
        return [
            f"wrote {wrapper}",
            '提示：把 export LITRADAR_API_KEY=sk-... 写进 ~/.config/litradar/env（chmod 600，别放进 vault）',
            f"plist: {mac_plist_path()}",
            f'launchctl bootstrap gui/$(id -u) "{mac_plist_path()}"',
            f'launchctl list | grep {MAC_LABEL}',
        ]
    return [
        f"wrote {wrapper}",
        "提示：把 export LITRADAR_API_KEY=sk-... 写进 ~/.config/litradar/env（chmod 600，别放进 vault）",
        f'crontab -l | grep -v litradar | {{ cat; echo \'{cron_line(wrapper, cfg)}\'; }} | crontab -',
    ]


def install(vault: Path | str, cfg: Config, *, apply: bool = False) -> list[str]:
    wrapper = write_wrapper(vault, cfg)
    key = platform_key()
    hour, minute = _time(cfg)
    if not apply:
        return print_commands(vault, cfg)

    if key == "win32":
        command = [
            "schtasks",
            "/Create",
            "/TN",
            TASK_NAME,
            "/SC",
            "DAILY",
            "/ST",
            f"{hour:02d}:{minute:02d}",
            "/F",
            "/TR",
            f'"{wrapper}"',
        ]
        subprocess.run(command, check=True)
        return [f"registered {TASK_NAME} at {hour:02d}:{minute:02d}"]

    if key == "darwin":
        plist = mac_plist_path()
        plist.parent.mkdir(parents=True, exist_ok=True)
        plist.write_text(mac_plist(wrapper, cfg), encoding="utf-8")
        uid = os.getuid()
        subprocess.run(["launchctl", "bootout", f"gui/{uid}", str(plist)], check=False,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        subprocess.run(["launchctl", "bootstrap", f"gui/{uid}", str(plist)], check=True)
        return [f"registered {MAC_LABEL} at {hour:02d}:{minute:02d} ({plist})"]

    existing = subprocess.run(["crontab", "-l"], capture_output=True, text=True, check=False).stdout
    kept = [line for line in existing.splitlines() if "litradar" not in line.lower()]
    kept.append(cron_line(wrapper, cfg))
    subprocess.run(["crontab", "-"], input="\n".join(kept) + "\n", text=True, check=True)
    return [f"registered cron entry at {hour:02d}:{minute:02d}"]


def uninstall(vault: Path | str, cfg: Config, *, apply: bool = False) -> list[str]:
    key = platform_key()
    plist = mac_plist_path()
    if key == "win32":
        commands = [f'schtasks /Delete /TN "{TASK_NAME}" /F']
        if apply:
            subprocess.run(["schtasks", "/Delete", "/TN", TASK_NAME, "/F"], check=False)
            return ["deleted scheduled task"]
        return commands
    if key == "darwin":
        commands = [
            f'launchctl bootout gui/$(id -u) "{plist}"',
            f'rm -f "{plist}"',
        ]
        if apply:
            subprocess.run(["launchctl", "bootout", f"gui/{os.getuid()}", str(plist)], check=False,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            try:
                plist.unlink()
            except OSError:
                pass
            return ["unregistered launchd agent"]
        return commands
    commands = ["crontab -l | grep -v litradar | crontab -"]
    if apply:
        existing = subprocess.run(["crontab", "-l"], capture_output=True, text=True, check=False).stdout
        kept = [line for line in existing.splitlines() if "litradar" not in line.lower()]
        subprocess.run(["crontab", "-"], input="\n".join(kept) + "\n", text=True, check=True)
        return ["removed cron entry"]
    return commands


def query(vault: Path | str) -> dict[str, Any]:
    """Best-effort "is the schedule registered?" probe for doctor/status."""
    key = platform_key()
    try:
        if key == "win32":
            result = subprocess.run(
                ["schtasks", "/Query", "/TN", TASK_NAME, "/FO", "LIST"],
                capture_output=True,
                text=True,
                check=False,
            )
            return {"installed": result.returncode == 0, "detail": result.stdout.strip()[:400]}
        if key == "darwin":
            result = subprocess.run(
                ["launchctl", "list"], capture_output=True, text=True, check=False
            )
            return {"installed": MAC_LABEL in result.stdout, "detail": MAC_LABEL}
        result = subprocess.run(["crontab", "-l"], capture_output=True, text=True, check=False)
        return {
            "installed": "litradar" in result.stdout.lower(),
            "detail": "crontab",
        }
    except OSError as exc:
        return {"installed": False, "detail": f"无法查询调度器：{exc}"}
