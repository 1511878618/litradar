"""Research profile: turn a Zotero collection into a direction string + keywords.

The point is to stop hand-maintaining `direction` in config.yaml: a collection of
papers a person actually saved is a better statement of interest than a sentence
written once and forgotten.  Pure functions here — the Zotero read lives in
``zotero.py`` so this is testable without a library.
"""

from __future__ import annotations

import re
from collections import Counter
from typing import Any

STOPWORDS = {
    "a", "an", "the", "of", "and", "or", "for", "to", "in", "on", "with", "by",
    "from", "at", "as", "is", "are", "was", "were", "be", "been", "being", "this",
    "that", "these", "those", "it", "its", "we", "our", "you", "your", "they",
    "their", "he", "she", "his", "her", "not", "no", "but", "if", "then", "than",
    "into", "via", "using", "use", "used", "based", "study", "studies", "paper",
    "research", "review", "analysis", "results", "method", "methods", "data",
    "new", "novel", "toward", "towards", "between", "among", "after", "before",
    "during", "can", "may", "could", "should", "would", "also", "more", "most",
    "such", "other", "has", "have", "had", "do", "does", "did",
}
# Zotero is full of workflow tags; they say nothing about the research direction.
JUNK_TAGS = {
    "/unread", "unread", "read", "to read", "review", "综述", "未读", "已读",
    "重要", "⭐", "⭐⭐", "⭐⭐⭐", "⭐⭐⭐⭐", "⭐⭐⭐⭐⭐", "🌝🌝🌝",
    "paper", "papers", "文献", "文章", "methods", "method", "writing", "写作参考",
    "必读", "经典", "good", "basic", "analysis", "data", "python", "latex",
}
_WORD = re.compile(r"[A-Za-z][A-Za-z0-9\-]{2,}")
_CJK = re.compile(r"[\u4e00-\u9fff]{2,10}")


def _clean_tag(tag: str) -> str:
    value = " ".join(str(tag or "").split()).strip(" ·-")
    if not value or "⭐" in value or "🌝" in value:
        return ""
    if value.casefold().startswith(("未命名", "unnamed")):
        return ""
    if value.isdigit():
        return ""
    return value


def _english_terms(text: str) -> list[str]:
    """Phrases and acronyms only: single words ("health", "records") are noise."""
    words = _WORD.findall(text or "")
    lowered = [word.lower() for word in words if word.lower() not in STOPWORDS]
    bigrams = [
        f"{lowered[index]} {lowered[index + 1]}"
        for index in range(len(lowered) - 1)
        if lowered[index] != lowered[index + 1]
    ]
    acronyms = [word for word in words if word.isupper() and 2 <= len(word) <= 6]
    return bigrams + acronyms


def _cjk_terms(text: str) -> list[str]:
    return [match.group(0) for match in _CJK.finditer(text or "")]


def build_profile(
    items: list[dict[str, Any]],
    *,
    collection: str | None = None,
    tag_counts: dict[str, int] | None = None,
    limit: int = 12,
) -> dict[str, Any]:
    """Return ``{direction, keywords, scanned, tags}`` from titles/abstracts/tags."""
    scores: Counter[str] = Counter()
    for tag, count in (tag_counts or {}).items():
        cleaned = _clean_tag(tag)
        if not cleaned or cleaned.casefold() in JUNK_TAGS or len(cleaned) < 2:
            continue
        scores[cleaned] += 3 * int(count or 1)

    for item in items:
        text = f"{item.get('title') or ''} {item.get('abstract') or ''}"
        for term in _english_terms(text):
            scores[term] += 1
        for term in _cjk_terms(str(item.get("title") or "")):
            scores[term] += 1

    keywords = [term for term, _ in scores.most_common(limit * 2)]
    # Drop substrings dominated by a longer phrase ("machine learning" vs "learning").
    picked: list[str] = []
    for term in keywords:
        if any(term != other and term in other for other in picked):
            continue
        picked.append(term)
        if len(picked) >= limit:
            break

    direction_parts = [collection] if collection else []
    direction_parts += picked[:4]
    direction = "；".join(part for part in direction_parts if part)
    return {
        "direction": direction,
        "keywords": picked,
        "scanned": len(items),
        "collection": collection or "",
    }


def to_yaml(profile: dict[str, Any], *, source: str = "zotero") -> str:
    """A paste-ready profile file (``.litradar/profile.yaml``)."""
    import json

    keywords = "".join(f"  - {json.dumps(word, ensure_ascii=False)}\n" for word in profile["keywords"])
    return (
        f"# generated by litradar from {source}\n"
        f"# {profile['scanned']} 篇（{profile.get('collection') or '整个文库'}）\n"
        f"direction: {json.dumps(profile['direction'], ensure_ascii=False)}\n"
        "keywords:\n" + keywords
    )


# --------------------------------------------------------------------------- LLM profile
SYSTEM_PROMPT = """你是科研画像助手。给你某位研究者 Zotero 收藏夹里的一批论文元数据
（标题、期刊、年份、标签、摘要节选），归纳他的科研画像。

硬性规则：
1. 输出单个 JSON 对象，不要解释文字、不要 Markdown 代码块，格式：
   {"direction": "一句话方向（中文，≤120 字）",
    "summary": "200–400 字中文描述：研究什么、用什么方法、关注哪些数据和问题",
    "keywords": ["5–12 个检索关键词，英文原词优先"],
    "research_questions": ["3–6 条他正在回答的科学问题"],
    "methods": ["3–6 个方法或数据源"]}
2. 只依据给定的论文元数据；不要编造没出现过的主题、机构、合作者或结论。
3. keywords 必须是能在论文标题/摘要里检索到的原词或短语（英文优先，如
   "EHR foundation models"），后续会用它们匹配新论文；不要用宽泛词（data、model、study）。
4. 不要写"国际领先""重大突破"这类评价。
5. 论文少或主题分散时，如实写少一点，不要凑数。"""

PROFILE_KEYS = ("direction", "summary", "keywords", "research_questions", "methods")


def build_digest(
    items: list[dict[str, Any]],
    tags: dict[str, int] | None = None,
    *,
    max_items: int = 120,
    abstract_chars: int = 400,
) -> dict[str, Any]:
    rows = []
    for item in items[:max_items]:
        data = item.get("data") if isinstance(item.get("data"), dict) else item
        rows.append({
            "title": str(data.get("title") or "")[:200],
            "journal": str(data.get("publicationTitle") or data.get("journal") or "")[:80],
            "date": str(data.get("date") or "")[:20],
            "tags": [str(tag.get("tag")) for tag in data.get("tags") or [] if isinstance(tag, dict)][:6],
            "abstract": str(data.get("abstractNote") or data.get("abstract") or "")[:abstract_chars],
        })
    top_tags = [tag for tag, _ in sorted((tags or {}).items(), key=lambda pair: -pair[1])[:30]]
    return {"papers": [row for row in rows if row["title"]], "tags": top_tags}


def build_messages(digest: dict[str, Any]) -> list[dict[str, str]]:
    import json

    user = (
        f"论文数量：{len(digest.get('papers') or [])}\n"
        f"常用标签：{', '.join(digest.get('tags') or []) or '（无）'}\n\n"
        + json.dumps(digest.get("papers") or [], ensure_ascii=False)
    )
    return [{"role": "system", "content": SYSTEM_PROMPT}, {"role": "user", "content": user}]


def parse_llm_payload(payload: Any) -> dict[str, Any] | None:
    if not isinstance(payload, dict):
        return None
    direction = " ".join(str(payload.get("direction") or "").split())
    summary = " ".join(str(payload.get("summary") or "").split())
    if not direction or not summary:
        return None

    def clean_list(raw: Any, limit: int, max_chars: int = 200) -> list[str]:
        if isinstance(raw, str):
            raw = [raw]
        if not isinstance(raw, list):
            return []
        out: list[str] = []
        for item in raw:
            text = " ".join(str(item).split())
            if text and text not in out:
                out.append(text[:max_chars])
        return out[:limit]

    keywords = clean_list(payload.get("keywords"), 15, 60)
    if len(keywords) < 3:
        return None
    return {
        "direction": direction[:200],
        "summary": summary[:1200],
        "keywords": keywords,
        "research_questions": clean_list(payload.get("research_questions"), 8),
        "methods": clean_list(payload.get("methods"), 8),
    }


def llm_profile(
    config: Any,
    items: list[dict[str, Any]],
    tags: dict[str, int] | None = None,
    *,
    logger: Any = None,
    usage: dict | None = None,
) -> dict[str, Any] | None:
    """Ask the model to synthesize a profile; ``None`` means "fall back"."""
    from . import llm

    digest = build_digest(items, tags)
    if not digest["papers"]:
        return None
    try:
        payload = llm.chat_json(config, build_messages(digest), logger=logger, usage=usage)
    except llm.LlmError:
        return None
    return parse_llm_payload(payload)


def render_markdown(profile: dict[str, Any]) -> str:
    lines = [
        f"# 科研画像：{profile.get('name') or 'default'}",
        "",
        f"> 来源：{('、'.join(profile.get('sources') or [])) or '—'}",
        f"> 生成时间：{profile.get('created_at') or ''}"
        f" · 模型：{profile.get('model') or 'deterministic'}",
        "",
        "## 方向",
        "",
        str(profile.get("direction") or ""),
        "",
        "## 描述",
        "",
        str(profile.get("summary") or ""),
        "",
        "## 关键词",
        "",
        "、".join(profile.get("keywords") or []) or "—",
        "",
    ]
    for title, key in (("研究问题", "research_questions"), ("方法与数据", "methods")):
        values = profile.get(key) or []
        if values:
            lines += [f"## {title}", ""]
            lines += [f"- {value}" for value in values]
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_profile_files(root: Any, name: str, profile: dict[str, Any]) -> tuple[Any, Any]:
    """Write ``profiles/<name>.yaml`` + ``.md``; returns the two paths."""
    import re
    from pathlib import Path

    import yaml

    directory = Path(root) / "profiles"
    directory.mkdir(parents=True, exist_ok=True)
    # Keep CJK (collection names are often Chinese); only strip path-hostile chars.
    slug = re.sub(r'[\\/:*?"<>|\s]+', "-", str(name).strip()).strip(".-") or "profile"
    yaml_path = directory / f"{slug}.yaml"
    md_path = directory / f"{slug}.md"
    payload = {**profile, "name": name}
    yaml_path.write_text(
        yaml.safe_dump(payload, allow_unicode=True, sort_keys=False), encoding="utf-8"
    )
    md_path.write_text(render_markdown(payload), encoding="utf-8")
    return yaml_path, md_path
