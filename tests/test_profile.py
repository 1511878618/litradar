"""Research profile from a Zotero collection: direction + keywords, no model needed."""

from helpers import make_config, temp_dir

from litradar.profile import build_profile, to_yaml


def _items(*titles):
    return [{"title": title, "abstractNote": ""} for title in titles]


def test_profile_prefers_phrases_and_tags():
    items = _items(
        "EHR foundation models for clinical prediction",
        "Patient representation learning with EHR foundation models",
        "Cross-site transfer of EHR foundation models",
    )
    tags = {"EHR foundation models": 4, "/unread": 10, "⭐⭐⭐": 3, "未命名": 2}
    built = build_profile(items, collection="EHR", tag_counts=tags)
    assert built["direction"].startswith("EHR；")
    assert "EHR foundation models" in built["keywords"]
    assert all("unread" not in word for word in built["keywords"])
    assert all("⭐" not in word for word in built["keywords"])


def test_profile_drops_single_words_and_keeps_acronyms():
    items = _items("GWAS of coronary artery disease", "GWAS meta analysis")
    built = build_profile(items, collection=None, tag_counts={})
    assert "GWAS" in built["keywords"]
    assert "gwas" not in built["keywords"]
    assert "coronary artery" in built["keywords"]


def test_profile_keeps_chinese_terms():
    items = _items("心血管疾病的风险预测模型", "心血管疾病与代谢组学")
    built = build_profile(items, collection="心血管", tag_counts={})
    assert built["direction"].startswith("心血管")
    assert any("心血管疾病" in word for word in built["keywords"])


def test_profile_yaml_roundtrip():
    built = build_profile(_items("Graph neural networks for proteins"), collection="GNN")
    text = to_yaml(built, source="Zotero GNN")
    assert text.startswith("# generated by litradar")
    assert "direction:" in text
    assert "keywords:" in text
    assert "graph neural" in text


def test_profile_file_overrides_direction_and_keywords():
    with temp_dir() as tmp:
        (tmp / ".litradar").mkdir(parents=True, exist_ok=True)
        (tmp / ".litradar" / "config.yaml").write_text(
            f'version: 1\nvault: "{tmp}"\ndirection: "旧方向"\n'
            "screening:\n  keywords: [old]\n",
            encoding="utf-8",
        )
        (tmp / ".litradar" / "profile.yaml").write_text(
            'direction: "EHR；clinical AI"\nkeywords:\n  - "EHR foundation models"\n  - "clinical prediction"\n',
            encoding="utf-8",
        )
        from litradar.config import load_config

        loaded = load_config(tmp)
        assert loaded.direction == "EHR；clinical AI"
        assert loaded.get("screening.keywords") == ["EHR foundation models", "clinical prediction"]


def test_digest_trims_abstracts_and_tags():
    from litradar.profile import build_digest

    items = [{"title": "A paper", "publicationTitle": "Cell", "date": "2026",
              "abstractNote": "x" * 900, "tags": [{"tag": "EHR"}]}]
    digest = build_digest(items, {"EHR": 3, "GWAS": 1}, max_items=10, abstract_chars=100)
    assert len(digest["papers"][0]["abstract"]) == 100
    assert digest["tags"] == ["EHR", "GWAS"]


def test_llm_payload_is_validated():
    from litradar.profile import parse_llm_payload

    good = {
        "direction": "EHR 与临床预测",
        "summary": "研究电子病历基础模型与临床风险预测。",
        "keywords": ["EHR foundation models", "clinical prediction", "UK Biobank"],
        "research_questions": ["EHR 能否跨站点迁移"],
        "methods": ["foundation models"],
    }
    parsed = parse_llm_payload(good)
    assert parsed and parsed["keywords"] == good["keywords"]

    assert parse_llm_payload({**good, "summary": ""}) is None
    assert parse_llm_payload({**good, "keywords": ["a", "b"]}) is None
    assert parse_llm_payload("not a dict") is None


def test_llm_profile_returns_none_without_key():
    from litradar.profile import llm_profile

    with temp_dir() as tmp:
        config = make_config(tmp)
        assert llm_profile(config, [{"title": "A", "abstractNote": "B"}], {}) is None


def test_write_profile_files_keeps_cjk_names():
    from litradar.profile import write_profile_files

    with temp_dir() as tmp:
        yaml_path, md_path = write_profile_files(tmp, "EHR+心血管", {
            "direction": "EHR；心血管",
            "keywords": ["EHR foundation models"],
            "summary": "描述",
            "research_questions": ["问题"],
            "methods": ["数据"],
            "sources": ["EHR", "心血管疾病"],
            "created_at": "2026-11-03T00:00:00+08:00",
            "model": "deterministic",
        })
        assert yaml_path.exists() and md_path.exists()
        assert "EHR+心血管" in yaml_path.name
        assert "# 科研画像：EHR+心血管" in md_path.read_text(encoding="utf-8")
